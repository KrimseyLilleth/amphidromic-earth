"""
Average NOAA ETOPO1 depths onto the 0.5 deg GOT4.10c tide grid (lon -180..179.5, lat -90..90).

Input: ETOPO1 sampled every 10 arc-minutes from NOAA ERDDAP:
  https://coastwatch.pfeg.noaa.gov/erddap/griddap/etopo180.nc?altitude[(-90.0):10:(90.0)][(-180.0):10:(180.0)]
Each 0.5 deg node takes the mean of the ocean (altitude < 0) samples in the 3x3 block around it.

Usage:
    python make_bathy_grid.py <etopo_10min.nc> <output .js>
"""
import sys, json, base64
import numpy as np
from scipy.io import netcdf_file


def main(nc_path, out_js):
    f = netcdf_file(nc_path, "r", mmap=False)
    alt = f.variables["altitude"][:].astype(float)        # (1081, 2161), 1/6 deg
    alt = alt[:, :-1]                                       # drop duplicate lon=180 column
    nlat, nlon = 361, 720
    depth = np.zeros((nlat, nlon))
    for j in range(nlat):
        rows = [r for r in (3*j - 1, 3*j, 3*j + 1) if 0 <= r < alt.shape[0]]
        for i in range(nlon):
            cols = [(3*i + d) % alt.shape[1] for d in (-1, 0, 1)]
            block = alt[np.ix_(rows, cols)]
            wet = block[block < 0]
            depth[j, i] = -wet.mean() if wet.size else 0.0
    d16 = depth.round().clip(0, 32767).astype("<i2")
    out = {"source": "NOAA ETOPO1 (via ERDDAP etopo180), 3x3 mean of 10' samples onto 0.5 deg",
           "nlat": nlat, "nlon": nlon, "b64": base64.b64encode(d16.tobytes()).decode()}
    with open(out_js, "w") as fo:
        fo.write("// Generated by make_bathy_grid.py from NOAA ETOPO1. Depth in metres, 0 = land.\n")
        fo.write("window.BATHY = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("max depth", depth.max(), "m; wet nodes", int((depth > 0).sum()), "; wrote", out_js)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
